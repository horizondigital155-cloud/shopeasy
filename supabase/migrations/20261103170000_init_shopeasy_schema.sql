CREATE TABLE IF NOT EXISTS email_otps (
  email TEXT PRIMARY KEY,
  otp_hash TEXT NOT NULL,
  purpose TEXT NOT NULL,
  phone TEXT,
  name TEXT,
  expires BIGINT NOT NULL,
  attempts BIGINT NOT NULL DEFAULT 0,
  last_sent BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS imported_products (
  name TEXT,
  category TEXT,
  unit TEXT,
  price BIGINT,
  price_type TEXT,
  image_search_url TEXT,
  product_search_url TEXT
);

CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY,
  category TEXT NOT NULL,
  name TEXT NOT NULL,
  unit TEXT NOT NULL DEFAULT '',
  price BIGINT NOT NULL,
  image TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  mrp BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL,
  name TEXT NOT NULL,
  address TEXT NOT NULL,
  items TEXT NOT NULL,
  subtotal BIGINT NOT NULL,
  fee BIGINT NOT NULL,
  total BIGINT NOT NULL,
  payment TEXT NOT NULL,
  payment_status TEXT NOT NULL DEFAULT 'pending',
  status TEXT NOT NULL DEFAULT 'placed',
  rider_id BIGINT,
  delivery_code_hash TEXT,
  delivery_code_exp BIGINT,
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  cancellation_reason TEXT,
  cancelled_at BIGINT
);

CREATE TABLE IF NOT EXISTS riders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT UNIQUE NOT NULL,
  hash TEXT NOT NULL,
  photo TEXT NOT NULL DEFAULT '',
  active BIGINT NOT NULL DEFAULT 1,
  created BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS product_images (
  product_id TEXT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
  filename TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS rider_earnings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
  rider_id BIGINT NOT NULL REFERENCES riders(id),
  amount BIGINT NOT NULL DEFAULT 5 CHECK (amount = 5),
  created BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS rider_locations (
  rider_id BIGINT PRIMARY KEY REFERENCES riders(id) ON DELETE CASCADE,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  updated BIGINT
);

CREATE TABLE IF NOT EXISTS service_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  phone TEXT NOT NULL,
  name TEXT NOT NULL,
  payload TEXT NOT NULL,
  fee BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  rider_id BIGINT,
  delivery_code_hash TEXT,
  delivery_code_exp BIGINT
);

CREATE TABLE IF NOT EXISTS service_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  phone TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  hash TEXT NOT NULL,
  created BIGINT NOT NULL,
  email TEXT
);

CREATE INDEX IF NOT EXISTS service_requests_phone_idx
ON service_requests(phone, id DESC);

CREATE INDEX IF NOT EXISTS service_requests_rider_idx
ON service_requests(rider_id, status, id DESC);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique
ON users(email)
WHERE email IS NOT NULL AND email <> '';
